// Turns the research paper into a TypeScript module the site can render.
//
// Generated at build time rather than fetched in the browser, so the paper is in the HTML that gets
// served: it is the most substantial thing on the site, and a recruiter or a search engine should
// not have to run JavaScript to read it.
//
//   node scripts/build-research.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { marked } from "marked";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "../docs/prediction-research.md");
const target = resolve(root, "lib/research-generated.ts");

if (!existsSync(source)) {
  console.error(`No research paper at ${source}`);
  process.exit(1);
}

const markdown = readFileSync(source, "utf8");

// Slugs have to be stable, because they become the anchor links in the contents list.
const slug = (text) =>
  text
    .toLowerCase()
    .replace(/[^\w\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-");

const headings = [];
const renderer = new marked.Renderer();
renderer.heading = ({ tokens, depth }) => {
  const text = tokens.map((t) => t.raw).join("");
  const id = slug(text);
  // Only the top two levels go in the contents; below that it is too long to be useful.
  if (depth <= 2) headings.push({ id, text, depth });
  return `<h${depth} id="${id}">${marked.parseInline(text)}</h${depth}>\n`;
};

// Tables are wide and scroll sideways. A region that scrolls has to be reachable from the keyboard,
// or someone without a mouse simply cannot read the right-hand columns, so each one is wrapped in a
// focusable labelled container rather than being made scrollable itself.
let tableCount = 0;
const baseTable = renderer.table.bind(renderer);
renderer.table = (token) => {
  tableCount += 1;
  return `<div class="paper-table" tabindex="0" role="region" aria-label="Table ${tableCount}">${baseTable(token)}</div>
`;
};

const html = marked.parse(markdown, { renderer, gfm: true, breaks: false });

const words = markdown.split(/\s+/).filter(Boolean).length;
const escaped = JSON.stringify(html);

writeFileSync(
  target,
  `// GENERATED by scripts/build-research.mjs from docs/prediction-research.md. Do not edit.
//
// The paper is the source of truth and lives in docs/. Re-run \`npm run research\` after changing it.

export interface ResearchHeading {
  id: string;
  text: string;
  depth: number;
}

export const RESEARCH_HTML: string = ${escaped};

export const RESEARCH_HEADINGS: ResearchHeading[] = ${JSON.stringify(headings, null, 2)};

export const RESEARCH_WORDS = ${words};
`,
  "utf8",
);

mkdirSync(resolve(root, "public"), { recursive: true });
// A copy people can download or link to directly.
writeFileSync(resolve(root, "public/prediction-research.md"), markdown, "utf8");

console.log(
  `research: ${words.toLocaleString()} words, ${headings.length} sections, ` +
    `${tableCount} tables -> lib/research-generated.ts`,
);
